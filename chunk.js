"use strict";
let border = 0.3;

class Chunk {
	constructor(values, x, y, z, resolution) {
		this.values = values;
		
		//this.types = Chunk.calculateTypes(values, resolution);
		
		this.x = x;
		this.y = y;
		this.z = z;
		this.center = [x + 8, y + 8, z + 8];

		this.meshes = [];
	}

	static calculateTypes(values, resolution) {
		const types = new Uint8Array(16*16*16);
		
		for(let x = 0; x < 16; x += resolution) {
			for(let y = 0; y < 16; y += resolution) {
				for(let z = 0; z < 16; z += resolution) {
					const coord = z*256 + y*16 + x;
					const coordLarge = (z+1)*361 + (y+1)*19 + (x+1);
					const type = 
						(values[coordLarge + regularVertexOffset[7]*resolution] < border)*128+
						(values[coordLarge + regularVertexOffset[6]*resolution] < border)*64 +
						(values[coordLarge + regularVertexOffset[5]*resolution] < border)*32 +
						(values[coordLarge + regularVertexOffset[4]*resolution] < border)*16 +
						(values[coordLarge + regularVertexOffset[3]*resolution] < border)*8  +
						(values[coordLarge + regularVertexOffset[2]*resolution] < border)*4  +
						(values[coordLarge + regularVertexOffset[1]*resolution] < border)*2  +
						(values[coordLarge + regularVertexOffset[0]*resolution] < border)
					;
					types[coord] = type;
				}
			}
		}

		return types;
	}
	
	marchCube(x, y, z, meshVertices, meshTriangles, meshNormals, terrain, resolution, types) {
		const coord = z*256 + y*16 + x;

		const type = types[coord];
		if(type == 0 || type == 255) {
			return;
		}
		
		const coordLarge = (z+1)*361 + (y+1)*19 + (x+1);
		
		const vertices = regularVertexData[type];
		const cubeX = x + this.x;
		const cubeY = y + this.y;
		const cubeZ = z + this.z;
		
		let vertex, startIndex, endIndex, startValue, endValue, interpolation, negInterpolation, vx, vy, vz, vExists;
		let vertexIndices = [];
		for(let v = 0; v < vertices.length; v++) {
			vertex = vertices[v];
			startIndex = vertex & 15;
			endIndex = (vertex >>> 4) & 15;
			startValue = this.values[coordLarge + regularVertexOffset[startIndex]*resolution];
			endValue = this.values[coordLarge + regularVertexOffset[endIndex]*resolution];

			interpolation = resolution * (border - startValue) / (endValue - startValue);
			negInterpolation = resolution - interpolation;
			
			vx = regularVertexCoords[startIndex*3    ]*negInterpolation + regularVertexCoords[endIndex*3    ]*interpolation + cubeX,
			vy = regularVertexCoords[startIndex*3 + 1]*negInterpolation + regularVertexCoords[endIndex*3 + 1]*interpolation + cubeY,
			vz = regularVertexCoords[startIndex*3 + 2]*negInterpolation + regularVertexCoords[endIndex*3 + 2]*interpolation + cubeZ
			vExists = false;
			for(let i = 0; i < meshVertices.length; i += 3) {
				if(meshVertices[i] == vx && meshVertices[i+1] == vy && meshVertices[i+2] == vz) {
					vertexIndices.push(i/3);
					vExists = true;
					break;
				}
			}
			if(!vExists) {
				meshVertices.push(vx, vy, vz);
				vertexIndices.push(meshVertices.length/3-1);
				
				const normal1 = terrain.getNormal(
					cubeX + regularVertexCoords[startIndex*3  ]*resolution,
					cubeY + regularVertexCoords[startIndex*3+1]*resolution,
					cubeZ + regularVertexCoords[startIndex*3+2]*resolution,
					resolution
				);
				const normal2 = terrain.getNormal(
					cubeX + regularVertexCoords[endIndex*3  ]*resolution,
					cubeY + regularVertexCoords[endIndex*3+1]*resolution,
					cubeZ + regularVertexCoords[endIndex*3+2]*resolution,
					resolution
				);
				
				meshNormals.push(
					(normal1[0]*negInterpolation + normal2[0]*interpolation),
					(normal1[1]*negInterpolation + normal2[1]*interpolation),
					(normal1[2]*negInterpolation + normal2[2]*interpolation)
				);
			}
		}
		
		const cellClass = regularCellClass[type];
		const triangles = regularCellData[cellClass];
		
		let i0, i1, i2;
		for(let i = 0; i < triangles.length; i += 3) {
			i0 = vertexIndices[triangles[i]];
			i1 = vertexIndices[triangles[i+1]];
			i2 = vertexIndices[triangles[i+2]];
			meshTriangles.push(i0, i1, i2);
		}
	}
	
	march(terrain, resolution) {
		const types = Chunk.calculateTypes(this.values, resolution);

		let meshVertices = [];
		let meshTriangles = [];
		let meshColors = [];
		let meshNormals = [];
		
		for(let x = 0; x < 16; x += resolution) {
			for(let y = 0; y < 16; y += resolution) {
				for(let z = 0; z < 16; z += resolution) {
					this.marchCube(x, y, z, meshVertices, meshTriangles, meshNormals, terrain, resolution, types);
				}
			}
		}

		let vertexColor;
		for(let i = 0; i < meshVertices.length; i += 3) {
			const l = 1 / Math.sqrt(meshNormals[i]**2 + meshNormals[i+1]**2 + meshNormals[i+2]**2);
			meshNormals[i] *= l;
			meshNormals[i+1] *= l;
			meshNormals[i+2] *= l;

			vertexColor = terrain.getColor(meshVertices[i+1], meshNormals[i+1]);
			meshColors.push(vertexColor[0], vertexColor[1], vertexColor[2], 1);
		}

		return new Mesh(meshVertices, meshTriangles, meshColors, meshNormals);
	}
}

